// Renders the "AI-generated preview" label once, on a machine that has fonts, and writes it into
// lib/tryon/ai-mark-image.ts as base64. The server only composites this image, because Vercel's
// servers have no fonts installed and text in SVG would not render there.
// Run again only to change the label: node scripts/make-ai-mark.mjs
import { writeFileSync } from "node:fs";
import sharp from "sharp";

const width = 935;
const height = 150;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
  <rect x="0" y="0" width="${width}" height="${height}" rx="34" fill="#000" fill-opacity="0.62"/>
  <g fill="#fff">
    <path d="M85 30 L97 63 L130 75 L97 87 L85 120 L73 87 L40 75 L73 63 Z"/>
  </g>
  <text x="160" y="101" font-family="Segoe UI, Arial, Helvetica, sans-serif" font-size="74" font-weight="600" fill="#fff">AI-generated preview</text>
</svg>`;

const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer();
const meta = await sharp(png).metadata();
writeFileSync(
  new URL("../lib/tryon/ai-mark-image.ts", import.meta.url),
  `// Generated by scripts/make-ai-mark.mjs. Do not edit by hand.\n` +
    `export const AI_MARK_PNG_BASE64 =\n  "${png.toString("base64")}";\n` +
    `export const AI_MARK_SIZE = { width: ${meta.width}, height: ${meta.height} };\n`,
);
writeFileSync(new URL("../ai-mark-preview.png", import.meta.url), png);
console.log(`wrote lib/tryon/ai-mark-image.ts (${png.length} bytes, ${meta.width}x${meta.height}); preview in ai-mark-preview.png`);
